package Polymorphism;

public class Demo1 
{

	
	//Non Static regular method
	public void m1()             //Method declaration
	{
		System.out.println("Hi");   //Method Definition/implementation
	}
	
	
	//Static regular method
	public static void m2()   //Method declaration
	{
		System.out.println("Hello");  //Method Definition/implementation
	}
	
	
	public static void main(String[] args)  //Method declaration
	{
		int a=10;
		System.out.println(a);    //Method Definition/implementation
	}
	
	
	
}

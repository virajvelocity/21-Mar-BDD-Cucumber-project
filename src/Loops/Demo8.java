package Loops;

public class Demo8 
{

	// Print 5 to 2 nos by using for loop-->5 4 3 2
			public static void main(String[] args)
			{
				     //i=5      //5>=2      //i=4
				                //4>=2      //i=3
				                //3>=2      //i=2
				                //2>=2      //i=1
				                //1>=2
				for(int i=5;      i>=2;       i-=1)   //i=i-1 == i--  == i-=1  
				{
					
					System.out.println(i);  //5  4  3  2
					
				}
				
				
				
			}
	
	
	
	
	
	
}

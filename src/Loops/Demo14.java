package Loops;

public class Demo14 
{
	//Print nos from 1 to 4---> 1 2 3 4
	public static void main(String[] args) 
	{     
		  //i=1
		int i=1;      	//starting condition
		
		    //1<=4
		    //2<=4
		   //3<=4
		    //4<=4
		   //5<=4
		while(i<=4)    	//End Condition
		{
			System.out.println(i);  //1  2  3  4
			
			i++;  //2   3   4   5
		}
		
	}
	
	

}

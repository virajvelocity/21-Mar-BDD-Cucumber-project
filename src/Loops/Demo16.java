package Loops;

public class Demo16 
{
   //Print nos from 2 to 6---> 2  3  4  5  6
	public static void main(String[] args) 
	{       //i=2
		  int i=2;   //Starting Condition
		
		
		  do 
		  {
			 
			  System.out.println(i);  //2  3    4   5   6
			 
			  //i=3 
			  //i=4
			  //i=5
			  //i=6 
			  //i=7 
			  i++;        // Increment
			  
		  }    //3<=6
		       //4<=6
		       //5<=6
		      //6<=6
		      //7<=6
		  while(i<=6);   //End Condition
		  
	}
	
	
	
	
	
	
}

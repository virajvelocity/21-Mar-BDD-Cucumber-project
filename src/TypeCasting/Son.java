package TypeCasting;

public class Son extends Father
{
	//Child Class/Sub Class
	
	//Car()  Money()   Home()

	public void Mobile() 
	{
		System.out.println("Samsung S24 Ultra");
	}
	
	//Overriding Method
	public void Car()    //Method Declaration
	{
		System.out.println("Kia Seltos");//Method Definition/Implementation
	}
	
	//Overriding Method
	public void Money()  //Method Declaration
	{
		System.out.println("5 Lakh");  //Method Definition/Implementation
	}
	
	
	
}
